const isDir = async p => (await stat(p).catch(() => undefined))?.isDirectory();

const readJson = async file => JSON.parse(await readFile(file, 'utf8'));

const readJsonLines = async file => {
  const text = await readFile(file, 'utf8').catch(() => '');
  const out = [];
  for (const line of text.split('\n')) {
    if (!line.trim()) continue;
    try {
      out.push(JSON.parse(line));
    } catch {
      // ignore a torn line
    }
  }
  return out;
};

const shortName = name => String(name).replace(/^thixotrope-harness-/, '');

/**
 * Load a session directory: workflows (finished and running), their agents,
 * the PM's direct agents and the PM transcript.
 * @param {string} dir
 */
export const loadSession = async dir => {
  const wfDir = path.join(dir, 'workflows');
  const agentsRoot = path.join(dir, 'subagents', 'workflows');
  /** @type {Map<string, any>} */
  const workflows = new Map();
  for (const n of await readdir(wfDir).catch(() => [])) {
    if (!n.endsWith('.json')) continue;
    const w = await readJson(path.join(wfDir, n)).catch(() => undefined);
    if (!w?.runId) continue;
    const labels = new Map();
    for (const p of w.workflowProgress ?? [])
      if (p?.type === 'workflow_agent' && p.agentId)
        labels.set(p.agentId, p.label);
    workflows.set(w.runId, {
      id: w.runId,
      name: shortName(w.workflowName ?? w.runId),
      status: w.status ?? 'completed',
      start: Number(w.startTime),
      end: Number(w.startTime) + Number(w.durationMs),
      labels,
      agents: [],
    });
  }
  for (const n of await readdir(path.join(wfDir, 'scripts')).catch(() => [])) {
    const m = /^(.*)-(wf_[\w-]+)\.js$/.exec(n);
    if (!m || workflows.has(m[2])) continue;
    workflows.set(m[2], {
      id: m[2],
      name: shortName(m[1]),
      status: 'running',
      start: NaN,
      end: NaN,
      labels: new Map(),
      agents: [],
    });
  }
  for (const id of await readdir(agentsRoot).catch(() => [])) {
    const d = path.join(agentsRoot, id);
    if (!(await isDir(d))) continue;
    let w = workflows.get(id);
    if (!w) {
      w = {
        id,
        name: id,
        status: 'running',
        start: NaN,
        end: NaN,
        labels: new Map(),
        agents: [],
      };
      workflows.set(id, w);
    }
    for (const j of await readJsonLines(path.join(d, 'journal.jsonl')))
      if (
        j.type === 'started' &&
        j.agentId &&
        j.label &&
        !w.labels.has(j.agentId)
      )
        w.labels.set(j.agentId, j.label);
    for (const n of (await readdir(d)).sort()) {
      const m = /^agent-(\w+)\.jsonl$/.exec(n);
      if (!m) continue;
      let label = w.labels.get(m[1]);
      if (!label) {
        const meta = await readJson(
          path.join(d, `agent-${m[1]}.meta.json`),
        ).catch(() => ({}));
        label = meta.description ?? m[1];
      }
      w.agents.push({
        key: `${id}/${m[1]}`,
        label,
        parsed: await parseFile(path.join(d, n)),
      });
    }
  }
  for (const w of workflows.values()) {
    const firsts = w.agents.map(a => a.parsed.first).filter(Number.isFinite);
    const lasts = w.agents.map(a => a.parsed.last).filter(Number.isFinite);
    if (!Number.isFinite(w.start) && firsts.length)
      w.start = Math.min(...firsts);
    if (!Number.isFinite(w.end) && lasts.length) w.end = Math.max(...lasts);
  }
  const list = [...workflows.values()]
    .filter(w => Number.isFinite(w.start))
    .sort((a, b) => a.start - b.start);
  const buildStart = list.length ? list[0].start : NaN;

  // The PM's direct agents within the build window, labelled by number only
  // (their descriptions are free text).
  const direct = [];
  const top = path.join(dir, 'subagents');
  for (const n of (await readdir(top).catch(() => [])).sort()) {
    const m = /^agent-(\w+)\.jsonl$/.exec(n);
    if (!m) continue;
    const parsed = await parseFile(path.join(top, n));
    if (!(parsed.first >= buildStart)) continue;
    direct.push({ key: `direct/${m[1]}`, label: '', parsed });
  }
  direct.sort((a, b) => a.parsed.first - b.parsed.first);
  direct.forEach((a, i) => {
    a.label = `PM direct agent ${i + 1}`;
  });

  const pmFile = `${dir.replace(/[/\\]+$/, '')}.jsonl`;
  const pm = (await stat(pmFile).catch(() => undefined))
    ? await parseFile(pmFile, { from: buildStart })
    : undefined;
  return { workflows: list, direct, pm };
};

/**
 * Union of intervals, clipped to [lo, hi].
 * @param {Array<[number, number]>} intervals
 */
export const union = intervals => {
  const s = intervals
    .filter(([a, b]) => Number.isFinite(a) && Number.isFinite(b) && b > a)
    .sort((x, y) => x[0] - y[0]);
  /** @type {Array<[number, number]>} */
  const out = [];
  for (const [a, b] of s) {
    const last = out[out.length - 1];
    if (last && a <= last[1]) last[1] = Math.max(last[1], b);
    else out.push([a, b]);
  }
  return out;
};

/**
 * PM working stretches: pieces of the PM transcript that are not idle.
 * @param {Parsed} pm
 */
const pmWorkIntervals = pm => {
  if (!pm?.events.length) return [];
  const fg = pm.calls.filter(c => !c.background);
  /** @type {Array<[number, number]>} */
  const out = [];
  const ev = pm.events;
  for (let i = 0; i + 1 < ev.length; i += 1) {
    const a = ev[i].t;
    const b = ev[i + 1].t;
    if (b <= a) continue;
    const busy =
      ev[i + 1].kind === 'assistant' ||
      fg.some(c => c.start <= a && c.end >= b && c.category !== 'subagent');
    if (busy) out.push([a, b]);
  }
  return union(out);
};

const overlap = (intervals, lo, hi) =>
  intervals.reduce(
    (s, [a, b]) => s + Math.max(0, Math.min(b, hi) - Math.max(a, lo)),
    0,
  );

/**
 * Build the report object.
 * @param {Awaited<ReturnType<typeof loadSession>>} session
 * @param {{ runs?: any[], commits?: number[], now?: number }} [extra]
 */
export const buildReport = (session, extra = {}) => {
  const { runs = [], commits = [] } = extra;
  const { workflows, direct, pm } = session;
  const allAgents = [...workflows.flatMap(w => w.agents), ...direct];
  const allCalls = [];
  for (const a of allAgents)
    for (const c of a.parsed.calls) {
      c.agentKey = a.key;
      allCalls.push(c);
    }
  assignLockWaits(allCalls);

  const totals = Object.fromEntries(CATEGORIES.map(c => [c, 0]));
  let agentMs = 0;
  let viaBackground = 0;
  /** @type {Array<[number, number]>} */
  const lockIntervals = [];
  const longest = [];
  const describe = (a, wfName) => {
    const s = splitAgent(a.parsed);
    for (const c of CATEGORIES) totals[c] += s.split[c];
    agentMs += s.wallMs;
    viaBackground += s.viaBackground;
    lockIntervals.push(...s.lockIntervals);
    for (const d of commandDurations(a.parsed.calls))
      longest.push({ ...d, workflow: wfName, agent: a.label });
    const { lockIntervals: _l, ...rest } = s;
    return { label: a.label, start: a.parsed.first, ...rest };
  };
  const wfRows = workflows.map(w => {
    const agents = w.agents
      .map(a => describe(a, w.name))
      .sort((x, y) => x.start - y.start);
    const wfCommits = commits.filter(t => t >= w.start && t <= w.end).length;
    return {
      name: w.name,
      status: w.status,
      start: w.start,
      end: w.end,
      wallMs: w.end - w.start,
      agents,
      agentMs: agents.reduce((s, a) => s + a.wallMs, 0),
      commits: wfCommits,
    };
  });
  const directRows = direct.map(a => describe(a, '(PM direct)'));

  const coverage = union([
    ...workflows.map(w => /** @type {[number, number]} */ ([w.start, w.end])),
    ...direct.map(
      a => /** @type {[number, number]} */ ([a.parsed.first, a.parsed.last]),
    ),
  ]);
  const ends = [
    ...workflows.map(w => w.end),
    ...direct.map(a => a.parsed.last),
    pm?.last ?? NaN,
  ].filter(Number.isFinite);
  const buildStart = workflows.length ? workflows[0].start : NaN;
  const buildEnd = ends.length ? Math.max(...ends) : NaN;
  const pmWork = pmWorkIntervals(/** @type {Parsed} */ (pm));
  const gaps = [];
  let cursor = buildStart;
  for (const [a, b] of coverage) {
    if (a > cursor) gaps.push([cursor, a]);
    cursor = Math.max(cursor, b);
  }
  if (buildEnd > cursor) gaps.push([cursor, buildEnd]);
  const gapRows = gaps.map(([a, b]) => ({
    start: a,
    end: b,
    ms: b - a,
    pmMs: overlap(pmWork, a, b),
    after:
      wfRows
        .filter(w => w.end <= a)
        .reduce(
          (/** @type {any} */ x, w) =>
            x === undefined || w.end >= x.end ? w : x,
          undefined,
        )?.name ?? '(start)',
    before: wfRows.find(w => w.start >= b)?.name ?? '(now)',
  }));
  const pmSplit = pm ? splitAgent(pm) : undefined;

  longest.sort((x, y) => y.ms - x.ms);
  const commandCount = longest.length;
  const runSummary = summariseRuns(runs);
  return {
    generatedAt: extra.now ?? Date.now(),
    buildStart,
    buildEnd,
    buildMs: buildEnd - buildStart,
    coveredMs: coverage.reduce((s, [a, b]) => s + (b - a), 0),
    gapMs: gapRows.reduce((s, g) => s + g.ms, 0),
    pmGapMs: gapRows.reduce((s, g) => s + g.pmMs, 0),
    pmWorkMs: pmWork.reduce((s, [a, b]) => s + (b - a), 0),
    pmSplit,
    agentCount: allAgents.length,
    agentMs,
    viaBackground,
    lockBusyMs: union(lockIntervals).reduce((t, [a, b]) => t + (b - a), 0),
    totals,
    workflows: wfRows,
    direct: directRows,
    gaps: gapRows,
    longest: longest.slice(0, 10),
    commandCount,
    longCommands: longest.filter(c => c.ms > 10 * 60_000).length,
    commits: commits.filter(t => !(t < buildStart)).length,
    runs: runSummary,
  };
};

/**
 * Summarise run-lock log lines by lane.
 * @param {any[]} runs
 */
export const summariseRuns = runs => {
  /** @type {Map<string, any>} */
  const lanes = new Map();
  for (const r of runs) {
    if (!r || typeof r !== 'object') continue;
    const lane = typeof r.lane === 'string' && r.lane ? r.lane : '(none)';
    const s = lanes.get(lane) ?? {
      lane,
      runs: 0,
      waitedMs: 0,
      heldMs: 0,
      timedOut: 0,
      failed: 0,
      maxHeldMs: 0,
    };
    s.runs += 1;
    s.waitedMs += Number(r.waitedMs) || 0;
    s.heldMs += Number(r.heldMs) || 0;
    s.maxHeldMs = Math.max(s.maxHeldMs, Number(r.heldMs) || 0);
    if (r.timedOut) s.timedOut += 1;
    // An in-process taker logs exitCode null: not known, not a failure.
    if (typeof r.exitCode === 'number' && r.exitCode !== 0) s.failed += 1;
    lanes.set(lane, s);
  }
  return [...lanes.values()].sort((a, b) => b.heldMs - a.heldMs);
};

/** @param {number} ms */
export const fmt = ms => {
  if (!Number.isFinite(ms)) return '-';
  const s = Math.round(ms / 1000);
  if (s < 60) return `${s}s`;
  const m = Math.floor(s / 60);
  if (m < 60) return `${m}m ${String(s % 60).padStart(2, '0')}s`;
  return `${Math.floor(m / 60)}h ${String(m % 60).padStart(2, '0')}m`;
};

const iso = t =>
  Number.isFinite(t)
    ? new Date(t).toISOString().slice(0, 16).replace('T', ' ')
    : '-';
const pct = (a, b) => (b > 0 ? `${((100 * a) / b).toFixed(1)} %` : '-');
const cell = s => String(s).replace(/\|/g, '/').replace(/\s+/g, ' ');
const hours = ms => (ms / 3_600_000).toFixed(1);

/**
 * Render the generated block (without markers).
 * @param {ReturnType<typeof buildReport>} r
 */
export const renderMarkdown = r => {
  const out = [];
  out.push(
    `Generated ${iso(r.generatedAt)} UTC from ${r.workflows.length} workflows, ${r.agentCount} agents and ${r.commandCount} shell commands. Times are UTC.`,
    '',
    '### Totals',
    '',
    '| measure | value |',
    '| --- | --- |',
    `| build wall time (first workflow start to last event) | ${fmt(r.buildMs)} |`,
    `| some workflow or agent running | ${fmt(r.coveredMs)} (${pct(r.coveredMs, r.buildMs)}) |`,
    `| nothing running (between workflows) | ${fmt(r.gapMs)} (${pct(r.gapMs, r.buildMs)}) |`,
    `| PM working while nothing ran | ${fmt(r.pmGapMs)} |`,
    `| PM working in all (model and tools, build window) | ${fmt(r.pmWorkMs)} |`,
    `| agent time, summed over agents | ${fmt(r.agentMs)} (${hours(r.agentMs)} h; ${(r.agentMs / Math.max(r.coveredMs, 1)).toFixed(1)} agents busy on average) |`,
    `| of which waiting on background jobs or polls (attributed) | ${fmt(r.viaBackground)} |`,
    `| wall time with some agent in a run-lock workload | ${fmt(r.lockBusyMs)} (${pct(r.lockBusyMs, r.buildMs)}) |`,
    `| shell commands over 10 minutes | ${r.longCommands} |`,
  );
  if (r.commits) out.push(`| commits in the window | ${r.commits} |`);
  out.push(
    '',
    '### Top time sinks (share of all agent time)',
    '',
    '| category | time | hours | share |',
    '| --- | --- | --- | --- |',
  );
  const sinks = CATEGORIES.map(
    c => /** @type {[string, number]} */ ([c, r.totals[c]]),
  ).sort((a, b) => b[1] - a[1]);
  for (const [c, ms] of sinks)
    if (ms > 0)
      out.push(
        `| ${CATEGORY_NAMES[c]} | ${fmt(ms)} | ${hours(ms)} | ${pct(ms, r.agentMs)} |`,
      );

  out.push(
    '',
    '### Workflows',
    '',
    '| workflow | status | start | end | wall | agents | agent time | commits |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
  );
  for (const w of r.workflows)
    out.push(
      `| ${cell(w.name)} | ${w.status} | ${iso(w.start)} | ${iso(w.end)} | ${fmt(w.wallMs)} | ${w.agents.length} | ${fmt(w.agentMs)} | ${w.commits || '-'} |`,
    );
  if (r.direct.length)
    out.push(
      `| (PM direct agents) | - | - | - | - | ${r.direct.length} | ${fmt(r.direct.reduce((s, a) => s + a.wallMs, 0))} | - |`,
    );

  const head = `| agent | wall | ${CATEGORIES.map(c => SHORT[c]).join(' | ')} |`;
  const rule = `| --- | --- | ${CATEGORIES.map(() => '---').join(' | ')} |`;
  const row = a =>
    `| ${cell(a.label)} | ${fmt(a.wallMs)} | ${CATEGORIES.map(c => (a.split[c] ? fmt(a.split[c]) : '')).join(' | ')} |`;
  for (const w of r.workflows) {
    out.push('', `#### ${cell(w.name)}`, '', head, rule);
    for (const a of w.agents) out.push(row(a));
  }
  if (r.direct.length) {
    out.push('', '#### PM direct agents', '', head, rule);
    for (const a of r.direct) out.push(row(a));
  }
  if (r.pmSplit) {
    out.push('', '#### PM (its own transcript, build window)', '', head, rule);
    out.push(row({ label: 'PM', ...r.pmSplit }));
  }

  out.push(
    '',
    '### Gaps: nothing running',
    '',
    '| after | before | start | length | PM working |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const g of r.gaps)
    out.push(
      `| ${cell(g.after)} | ${cell(g.before)} | ${iso(g.start)} | ${fmt(g.ms)} | ${fmt(g.pmMs)} |`,
    );

  out.push(
    '',
    '### Ten longest single commands',
    '',
    '| # | duration | category | workflow | agent |',
    '| --- | --- | --- | --- | --- |',
  );
  r.longest.forEach((c, i) => {
    const how = c.background
      ? ' (background job)'
      : c.poll
        ? ' (poll loop)'
        : '';
    out.push(
      `| ${i + 1} | ${fmt(c.ms)} | ${CATEGORY_NAMES[c.category]}${how} | ${cell(c.workflow)} | ${cell(c.agent)} |`,
    );
  });

  out.push('', '### Run-lock log', '');
  if (!r.runs.length) out.push('No run-lock log lines yet.');
  else {
    out.push(
      '| lane | runs | waited | held | longest held | timed out | failed |',
      '| --- | --- | --- | --- | --- | --- | --- |',
    );
    for (const s of r.runs)
      out.push(
        `| ${cell(s.lane)} | ${s.runs} | ${fmt(s.waitedMs)} | ${fmt(s.heldMs)} | ${fmt(s.maxHeldMs)} | ${s.timedOut} | ${s.failed} |`,
      );
  }
  return out.join('\n');
};

/**
 * Replace the generated block of `existing`, or append one.
 * @param {string} existing
 * @param {string} block
 */
export const replaceBlock = (existing, block) => {
  const inner = `${BEGIN}\n${block.trim()}\n${END}`;
  const b = existing.indexOf(BEGIN);
  const e = existing.indexOf(END, b < 0 ? 0 : b);
  if (b >= 0 && e > b)
    return existing.slice(0, b) + inner + existing.slice(e + END.length);
  const sep =
    existing && !existing.endsWith('\n') ? '\n\n' : existing ? '\n' : '';
  return `${existing}${sep}${inner}\n`;
};

const gitCommitTimes = range => {
  try {
    const text = execFileSync('git', ['log', '--format=%ct', range], {
      cwd: here,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    });
    return text
      .split('\n')
      .filter(Boolean)
      .map(s => Number(s) * 1000);
  } catch {
    return [];
  }
};

/** @param {string[]} argv */
export const parseArgs = argv => {
  /** @type {Record<string, any>} */
  const o = { stdout: false, json: false };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === '--out') o.out = argv[(i += 1)];
    else if (a === '--runs') o.runs = argv[(i += 1)];
    else if (a === '--git-range') o.gitRange = argv[(i += 1)];
    else if (a === '--stdout') o.stdout = true;
    else if (a === '--json') o.json = true;
    else if (!a.startsWith('--') && o.dir === undefined) o.dir = a;
    else throw Error(`unknown argument ${a}`);
  }
  return o;
};

const main = async () => {
  const opts = parseArgs(process.argv.slice(2));
  const dir = opts.dir ?? process.env.THIX_PROCESS_SESSION_DIR;
  if (!dir) {
    process.stderr.write(
      'Usage: process-time.mjs <session-dir> [--out FILE] [--runs FILE] [--git-range A..B] [--stdout] [--json]\n',
    );
    process.exitCode = 2;
    return;
  }
  const home =
    process.env.THIX_HARNESS_HOME ||
    path.join(os.homedir(), '.cache', 'thixotrope-harness');
  const runs = await readJsonLines(opts.runs ?? path.join(home, 'runs.jsonl'));
  const commits = opts.gitRange ? gitCommitTimes(opts.gitRange) : [];
  const session = await loadSession(dir);
  const report = buildReport(session, { runs, commits });
  if (opts.json) {
    process.stdout.write(`${JSON.stringify(report, null, 1)}\n`);
    return;
  }
  const block = renderMarkdown(report);
  if (opts.stdout) {
    process.stdout.write(`${block}\n`);
    return;
  }
  const out = opts.out ?? defaultOut;
  const existing = await readFile(out, 'utf8').catch(() => '');
  await writeFile(out, replaceBlock(existing, block));
  process.stderr.write(`process-time: wrote ${path.basename(out)}\n`);
};

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === url.fileURLToPath(import.meta.url)
) {
  main().catch(error => {
    process.stderr.write(`process-time: ${error?.message ?? error}\n`);
    process.exitCode = 1;
  });
}
