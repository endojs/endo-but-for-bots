/**
 * How the build's time is spent: a measured record from the PM session's
 * transcripts (workflows, their agents, the PM itself) and the run-lock log.
 *
 * Usage:
 *   node scripts/process-time.mjs <session-dir> [--out FILE] [--runs FILE]
 *     [--git-range A..B] [--stdout] [--json]
 *
 * <session-dir> (or THIX_PROCESS_SESSION_DIR) is the PM session's directory:
 * it holds `subagents/` (one transcript per agent, workflow agents under
 * `subagents/workflows/<run id>/`), `workflows/*.json` (finished workflows)
 * and `workflows/scripts/*.js`; the PM's own transcript is `<session-dir>.jsonl`.
 * `--runs` defaults to `<THIX_HARNESS_HOME>/runs.jsonl` (THIX_HARNESS_HOME
 * defaults to `<home>/.cache/thixotrope-harness`); a missing file is fine.
 * `--out` defaults to TIMELOG.md beside this package: only the block between
 * the two marker lines is rewritten.
 *
 * Method. Every tool call is the interval from the assistant line that asks
 * for it to the user line that carries its result. Within one agent the wall
 * time is cut at every timestamp; each piece goes to the highest-priority
 * category among the calls in flight, else to model time when the next line
 * is the model's, else to idle (the agent waits for a background job or a
 * notification; idle is attributed to the background job in flight, if any).
 * Polling loops (`until ...; sleep`) are attributed by their own words, then
 * by the background jobs in flight. A locked call whose output has the run
 * lock's "waiting" line waits until the last other locked call that was in
 * flight when it started has ended.
 *
 * The report holds only durations, counts, agent labels, workflow names and
 * category names: never command text, prompts, messages or paths.
 */
