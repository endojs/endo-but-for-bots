/**
 * The category of a shell command (never returned or printed: only the
 * category leaves this function).
 * @param {string} command
 * @returns {{ category: string, poll: boolean }}
 */
export const categorizeCommand = command => {
  const text = String(command ?? '');
  if (POLL_RE.test(text)) {
    if (CARGO_RE.test(text)) return { category: 'cargo', poll: true };
    if (LOCK_RE.test(text) || LOOSE_LOCK_RE.test(text))
      return { category: 'lockHold', poll: true };
    if (PROBE_RE.test(text)) return { category: 'probe', poll: true };
    if (DEPS_RE.test(text) || /install/.test(text))
      return { category: 'deps', poll: true };
    if (TESTS_RE.test(text) || /passed|failed|✘/.test(text))
      return { category: 'tests', poll: true };
    return { category: 'idle', poll: true };
  }
  if (LOCK_RE.test(text)) return { category: 'lockHold', poll: false };
  if (CARGO_RE.test(text)) return { category: 'cargo', poll: false };
  if (PY_EDIT_RE.test(text)) return { category: 'edit', poll: false };
  if (PROBE_RE.test(text)) return { category: 'probe', poll: false };
  if (DEPS_RE.test(text)) return { category: 'deps', poll: false };
  if (TESTS_RE.test(text)) return { category: 'tests', poll: false };
  if (LINT_RE.test(text)) return { category: 'lint', poll: false };
  if (GIT_RE.test(text)) return { category: 'git', poll: false };
  // Read-only when every segment's first word is a reading command.
  const segments = text
    .split(/&&|\|\||;|\|/)
    .map(s => s.trim())
    .filter(Boolean)
    .filter(s => !/^cd\s/.test(s));
  if (
    segments.length > 0 &&
    segments.every(s => READ_WORDS.has(s.split(/\s+/)[0]))
  )
    return { category: 'read', poll: false };
  return { category: 'shell', poll: false };
};

/**
 * @param {string} name tool name
 * @param {any} input
 * @returns {{ category: string, poll: boolean }}
 */
export const categorizeTool = (name, input) => {
  switch (name) {
    case 'Bash':
      return categorizeCommand(input?.command);
    case 'Read':
    case 'Grep':
    case 'Glob':
    case 'LS':
    case 'NotebookRead':
      return { category: 'read', poll: false };
    case 'Edit':
    case 'Write':
    case 'MultiEdit':
    case 'NotebookEdit':
      return { category: 'edit', poll: false };
    case 'Agent':
    case 'Task':
      return { category: 'subagent', poll: false };
    default:
      return { category: 'tools', poll: false };
  }
};

/**
 * @typedef {{
 *   id: string, tool: string, category: string, poll: boolean,
 *   background: boolean, start: number, end: number, resultAt?: number,
 *   waiting: boolean, waitUntil?: number, agentKey?: string,
 * }} Call
 * @typedef {{ t: number, kind: 'assistant' | 'user' | 'note' }} Event
 * @typedef {{ events: Event[], calls: Call[], first: number, last: number }} Parsed
 */

const contentText = content =>
  typeof content === 'string' ? content : JSON.stringify(content ?? '');

/**
 * Fold transcript records (parsed JSON lines) into events and calls. Keeps
 * no text: only times, tool names, categories and flags.
 * @param {Iterable<any>} records
 * @param {{ from?: number, to?: number }} [window]
 * @returns {Parsed}
 */
export const parseRecords = (records, window = {}) => {
  const { from = -Infinity, to = Infinity } = window;
  /** @type {Event[]} */
  const events = [];
  /** @type {Map<string, any>} */
  const calls = new Map();
  for (const o of records) {
    if (!o || typeof o !== 'object') continue;
    const t = Date.parse(o.timestamp);
    if (!Number.isFinite(t) || t < from || t > to) continue;
    if (o.type === 'assistant') {
      events.push({ t, kind: 'assistant' });
      const content = o.message?.content;
      if (Array.isArray(content))
        for (const b of content) {
          if (b?.type !== 'tool_use' || typeof b.id !== 'string') continue;
          const { category, poll } = categorizeTool(b.name, b.input);
          calls.set(b.id, {
            id: b.id,
            tool: String(b.name),
            category,
            poll,
            background: Boolean(b.input?.run_in_background),
            start: t,
            end: undefined,
            waiting: false,
          });
        }
    } else if (o.type === 'user') {
      events.push({ t, kind: 'user' });
      const content = o.message?.content;
      if (Array.isArray(content))
        for (const b of content) {
          if (b?.type !== 'tool_result') continue;
          const call = calls.get(b.tool_use_id);
          if (!call) continue;
          if (call.background) {
            // The immediate result only says the job started.
            call.resultAt = t;
            continue;
          }
          call.end = t;
          if (
            call.category === 'lockHold' &&
            WAITING_RE.test(contentText(b.content))
          )
            call.waiting = true;
        }
    } else if (o.type === 'attachment') {
      const prompt = o.attachment?.prompt;
      if (
        typeof prompt === 'string' &&
        prompt.includes('<task-notification>')
      ) {
        events.push({ t, kind: 'note' });
        const m = /<tool-use-id>([^<]+)<\/tool-use-id>/.exec(prompt);
        const call = m && calls.get(m[1]);
        if (call && call.background && call.end === undefined) call.end = t;
      }
    }
  }
  events.sort((a, b) => a.t - b.t);
  const first = events.length ? events[0].t : NaN;
  const last = events.length ? events[events.length - 1].t : NaN;
  const list = [...calls.values()].map(c => {
    // A call never answered ran to the end of what we saw.
    const end = c.end ?? (c.background ? last : (c.resultAt ?? last));
    const { resultAt: _r, ...rest } = /** @type {any} */ (c);
    return { ...rest, end: Math.max(end, c.start) };
  });
  return { events, calls: list, first, last };
};

/**
 * Stream a JSONL file into parseRecords.
 * @param {string} file
 * @param {{ from?: number, to?: number }} [window]
 */
export const parseFile = async (file, window) => {
  const records = [];
  const rl = readline.createInterface({
    input: createReadStream(file),
    crlfDelay: Infinity,
  });
  for await (const line of rl) {
    if (!line) continue;
    // Skip the bulky request blobs without parsing them.
    if (line.startsWith('{"type":"api-request')) continue;
    try {
      const o = JSON.parse(line);
      records.push({
        type: o.type,
        timestamp: o.timestamp,
        message:
          o.type === 'assistant' || o.type === 'user'
            ? { content: o.message?.content }
            : undefined,
        attachment:
          o.type === 'attachment'
            ? { prompt: o.attachment?.prompt }
            : undefined,
      });
    } catch {
      // A partial last line of a running transcript.
    }
  }
  return parseRecords(records, window);
};

/**
 * Estimate the lock wait of every locked call that printed "waiting": it
 * waits until the last other locked call in flight at its start has ended.
 * @param {Call[]} calls every call of every agent, with agentKey
 */
export const assignLockWaits = calls => {
  const locked = calls
    .filter(c => c.category === 'lockHold' && !c.poll)
    .sort((a, b) => a.start - b.start);
  for (const c of locked) {
    if (!c.waiting || c.end === undefined) continue;
    let until = c.start;
    for (const o of locked) {
      if (o === c || o.agentKey === c.agentKey) continue;
      if (o.start > c.start) break;
      if (o.end !== undefined && o.end > c.start && o.end < c.end)
        until = Math.max(until, o.end);
    }
    c.waitUntil = until;
  }
};

/**
 * Split one agent's wall time into categories.
 * @param {Parsed} parsed
 * @returns {{ wallMs: number, split: Record<string, number>, viaBackground: number, lockIntervals: Array<[number, number]> }}
 */
export const splitAgent = parsed => {
  /** @type {Record<string, number>} */
  const split = Object.fromEntries(CATEGORIES.map(c => [c, 0]));
  /** @type {Array<[number, number]>} */
  const lockIntervals = [];
  const { events, calls } = parsed;
  if (!events.length)
    return { wallMs: 0, split, viaBackground: 0, lockIntervals };
  /**
   * @param {string} cat
   * @param {number} a
   * @param {number} b
   */
  const add = (cat, a, b) => {
    split[cat] += b - a;
    if (cat === 'lockHold') lockIntervals.push([a, b]);
  };
  const lo = parsed.first;
  const hi = parsed.last;
  const points = new Set([lo, hi]);
  for (const e of events) points.add(e.t);
  for (const c of calls) {
    for (const p of [c.start, c.end, c.waitUntil])
      if (p !== undefined && p >= lo && p <= hi) points.add(p);
  }
  const sorted = [...points].sort((a, b) => a - b);
  const fg = calls.filter(c => !c.background).sort((a, b) => a.start - b.start);
  const bg = calls.filter(c => c.background).sort((a, b) => a.start - b.start);
  let viaBackground = 0;
  let ei = 0;
  for (let i = 0; i + 1 < sorted.length; i += 1) {
    const a = sorted[i];
    const b = sorted[i + 1];
    const span = b - a;
    if (span <= 0) continue;
    while (ei < events.length && events[ei].t < b) ei += 1;
    const next = events[ei];
    /** @type {string | undefined} */
    let best;
    let pollOnly = true;
    for (const c of fg) {
      if (c.start > a) break;
      if (c.end < b) continue;
      let cat = c.category;
      if (cat === 'lockHold' && c.waitUntil !== undefined && b <= c.waitUntil)
        cat = 'lockWait';
      if (c.poll && cat === 'idle') continue; // attributed below
      if (!c.poll) pollOnly = false;
      if (best === undefined || rank.get(cat) < rank.get(best)) best = cat;
    }
    const polling = fg.some(c => c.poll && c.start <= a && c.end >= b);
    if (best === undefined && !polling && next?.kind === 'assistant') {
      add('model', a, b);
      continue;
    }
    if (best === undefined || (pollOnly && polling)) {
      // Waiting: a poll loop or an idle stretch; attribute to background work.
      let bgBest;
      for (const c of bg) {
        if (c.start > a) break;
        if (c.end < b) continue;
        if (bgBest === undefined || rank.get(c.category) < rank.get(bgBest))
          bgBest = c.category;
      }
      const pick =
        best !== undefined &&
        (bgBest === undefined || rank.get(best) <= rank.get(bgBest))
          ? best
          : bgBest;
      if (pick !== undefined && pick !== 'idle') {
        add(pick, a, b);
        viaBackground += span;
        continue;
      }
      add('idle', a, b);
      continue;
    }
    add(best, a, b);
  }
  return { wallMs: hi - lo, split, viaBackground, lockIntervals };
};

