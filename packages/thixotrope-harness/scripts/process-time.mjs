const LOCK_RE =
  /run-lock\.mjs|test:integration|THIX_HARNESS_(?:INTEGRATION|SPIKES)=1|perf\/_harness|yarn perf\b|\.perf\.mjs|test\/(?:integration|template|spikes)\//;
