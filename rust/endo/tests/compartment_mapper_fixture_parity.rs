/// Absolute path to `packages/compartment-mapper/test`, resolved from
/// this crate's manifest directory (`rust/endo`).
fn fixtures_root() -> PathBuf {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/compartment-mapper/test");
    root.canonicalize().unwrap_or_else(|e| {
        panic!(
            "compartment-mapper fixtures directory not found at {}: {e}. \
             This parity harness expects the fixtures in place under \
             packages/compartment-mapper/test.",
            root.display()
        )
    })
}

/// The `fixtures-*` directory names actually present on disk.
fn on_disk_fixture_dirs(root: &Path) -> BTreeSet<String> {
    std::fs::read_dir(root)
        .unwrap_or_else(|e| panic!("cannot read fixtures root {}: {e}", root.display()))
        .filter_map(|entry| entry.ok())
        .filter(|entry| entry.path().is_dir())
        .filter_map(|entry| entry.file_name().into_string().ok())
        .filter(|name| name.starts_with("fixtures-"))
        .collect()
}

/// The `fixtures-*` directory names accounted for in [`MANIFEST`].
fn manifest_fixture_dirs() -> BTreeSet<String> {
    MANIFEST.iter().map(|(name, _)| name.to_string()).collect()
}

// Structural projection & golden diff
//
// The parity comparison is made on a *projection* of the compartment
// map, not its raw form, under two canonicalisations that both this
// harness and the node oracle apply identically (see
// `rust/endo/tools/gen-parity-golden.mjs` for the authoritative prose):
//
//   1. Compartments are keyed by `name`, not the version-suffixed
//      `<name>-v<version>` id (endor defaults an absent version to
//      0.0.0, compartment-mapper leaves it empty; version-string
//      parity is out of the walker's scope).
//   2. A module whose specifier ends in a bare `.js` records the
//      language family `"js"` rather than `mjs`/`cjs`, because the
//      mjs-vs-cjs classification of a `.js` file depends on the
//      package's `type` field, which endor's extension-only classifier
//      does not yet read. Unambiguous extensions keep their language.

/// One compartment's projected module table: specifier → `"lang:<x>"`
/// for a file module, or `"link:<targetCompartmentName>"` for a
/// cross-compartment (or self) link. Ordered for a stable diff.
type ProjectedCompartment = BTreeMap<String, String>;

/// A projected compartment map: entry (compartment name, module
/// specifier) plus compartment-name → module table.
struct Projected {
    entry_compartment: String,
    entry_module: String,
    compartments: BTreeMap<String, ProjectedCompartment>,
}

#[derive(Debug, Default, PartialEq, Eq)]
struct ExpectedHooks {
    exit_module_imports: Vec<String>,
    module_sources: Vec<(String, String)>,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Projection {
    /// Full archive projection: file languages, links, exits, and deferred
    /// errors.
    Archive,
    /// The package classifier's stable surface: compartment identities and
    /// cross-compartment dependency links. Group D uses this for deliberately
    /// excluded source edges; Group B uses it where dynamic package edges are
    /// not represented completely in the archive map. The node oracle is
    /// `mapNodeModules` itself for these fixtures.
    DependencyClassification,
    /// Archive projection for Group F's emulated host hooks. Node keeps an
    /// exit-hook record outside the archive and resolves it when importing;
    /// endor materializes equivalent source in the CAS. The synthetic file is
    /// therefore omitted from the structural map while hook invocations and
    /// real execution are asserted separately.
    ArchiveHostHooks,
}

/// The projected compartment key: the package `name` plus any
/// duplicate-copy disambiguation suffix (`-n1`, `-n2`, …) carried by the
/// compartment id. The version segment (`-v<version>`) is dropped —
/// endor defaults an absent version to `0.0.0` while compartment-mapper
/// leaves it empty, and version-string parity is out of the walker's
/// scope (rule 1) — but the `-n<k>` disambiguator IS part of the graph's
/// identity for a fixture with duplicate name/version copies
/// (`fixtures-stability`, `fixtures-1`), so it is preserved. The
/// disambiguator is always the id's trailing `-n<digits>` (it is appended
/// last by both engines); a package `name`/`version` that itself ends in
/// `-n<digits>` is out of scope for these fixtures.
fn projected_key(name: &str, id: &str) -> String {
    let unscoped = name.rsplit('/').next().unwrap_or(name);
    if let Some(pos) = id.rfind("-n") {
        let tail = &id[pos + 2..];
        if !tail.is_empty() && tail.bytes().all(|b| b.is_ascii_digit()) {
            return format!("{unscoped}{}", &id[pos..]);
        }
    }
    unscoped.to_string()
}

/// Normalise a parser tag + specifier to the canonical language (rule 2
/// above). `.js` ⇒ `"js"`; everything else keeps its base language.
fn canonical_language(parser: &str, specifier: &str) -> String {
    let base = match parser {
        "mjs" | "pre-mjs-json" => "mjs",
        "cjs" | "pre-cjs-json" => "cjs",
        "json" | "pre-json" => "json",
        other => other,
    };
    if specifier.ends_with(".js") && (base == "mjs" || base == "cjs") {
        "js".to_string()
    } else {
        base.to_string()
    }
}

/// Project endor's live compartment map into the comparison shape.
fn project_endor(map: &xsnap::archive::CompartmentMap, projection: Projection) -> Projected {
    use xsnap::archive::ModuleDescriptor::*;

    let id_to_key: BTreeMap<&str, String> = map
        .compartments
        .iter()
        .map(|(id, c)| (id.as_str(), projected_key(&c.name, id)))
        .collect();
    let key_of = |compartment_id: &str| -> String {
        id_to_key
            .get(compartment_id)
            .cloned()
            .unwrap_or_else(|| compartment_id.to_string())
    };

    let mut compartments = BTreeMap::new();
    for (id, c) in map.compartments.iter() {
        let self_key = key_of(id);
        let mut modules = ProjectedCompartment::new();
        for (spec, desc) in &c.modules {
            if projection == Projection::DependencyClassification {
                let Link { compartment, .. } = desc else {
                    continue;
                };
                let target = key_of(compartment);
                if target != self_key {
                    modules.insert(spec.clone(), format!("link:{target}"));
                }
                continue;
            }
            let value = match desc {
                File {
                    parser, location, ..
                } => {
                    if projection == Projection::ArchiveHostHooks
                        && location
                            .as_deref()
                            .is_some_and(|value| value.starts_with("__synthetic_"))
                    {
                        continue;
                    }
                    format!("lang:{}", canonical_language(parser, spec))
                }
                Link { compartment, .. } => {
                    format!("link:{}", key_of(compartment))
                }
                Exit { exit } => format!("exit:{exit}"),
                DeferredError { .. } => "deferredError".to_string(),
            };
            modules.insert(spec.clone(), value);
        }
        compartments.insert(self_key, modules);
    }

    let entry_compartment = key_of(map.entry.compartment.as_str());

    Projected {
        entry_compartment,
        entry_module: map.entry.module.clone(),
        compartments,
    }
}

/// Parse a committed golden JSON into the same comparison shape.
fn parse_golden(path: &Path) -> (Projection, Projected, ExpectedHooks) {
    let text = std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("cannot read golden {}: {e}", path.display()));
    let v: serde_json::Value = serde_json::from_str(&text)
        .unwrap_or_else(|e| panic!("golden {} is not valid JSON: {e}", path.display()));

    let entry_compartment = v["entryCompartment"]
        .as_str()
        .unwrap_or_else(|| panic!("golden {} missing entryCompartment", path.display()))
        .to_string();
    let entry_module = v["entryModule"]
        .as_str()
        .unwrap_or_else(|| panic!("golden {} missing entryModule", path.display()))
        .to_string();

    let mut compartments = BTreeMap::new();
    let comp_obj = v["compartments"]
        .as_object()
        .unwrap_or_else(|| panic!("golden {} missing compartments object", path.display()));
    for (name, comp) in comp_obj {
        let mut modules = ProjectedCompartment::new();
        let mods = comp["modules"].as_object().unwrap_or_else(|| {
            panic!(
                "golden {} compartment {name} missing modules",
                path.display()
            )
        });
        for (spec, desc) in mods {
            let value = if let Some(lang) = desc["language"].as_str() {
                format!("lang:{lang}")
            } else if let Some(link) = desc["link"].as_str() {
                format!("link:{link}")
            } else if let Some(exit) = desc["exit"].as_str() {
                format!("exit:{exit}")
            } else if desc.get("deferredError").is_some() {
                "deferredError".to_string()
            } else {
                panic!(
                    "golden {} module {spec} has no recognised descriptor ({desc})",
                    path.display()
                )
            };
            modules.insert(spec.clone(), value);
        }
        compartments.insert(name.clone(), modules);
    }

    let projection = match v.get("projection").and_then(|value| value.as_str()) {
        Some("dependency-classification") => Projection::DependencyClassification,
        Some("archive-host-hooks") => Projection::ArchiveHostHooks,
        Some(other) => panic!("golden {} has unknown projection {other:?}", path.display()),
        None => Projection::Archive,
    };

    let expected_hooks = if let Some(hooks) = v.get("emulatedHooks") {
        let exit_module_imports = hooks["exitModuleImports"]
            .as_array()
            .unwrap_or_else(|| {
                panic!(
                    "golden {} emulatedHooks.exitModuleImports is not an array",
                    path.display()
                )
            })
            .iter()
            .map(|value| {
                value
                    .as_str()
                    .unwrap_or_else(|| {
                        panic!(
                            "golden {} has a non-string exit-module observation",
                            path.display()
                        )
                    })
                    .to_string()
            })
            .collect();
        let module_sources = hooks["moduleSources"]
            .as_array()
            .unwrap_or_else(|| {
                panic!(
                    "golden {} emulatedHooks.moduleSources is not an array",
                    path.display()
                )
            })
            .iter()
            .map(|value| {
                let origin = value["origin"].as_str().unwrap_or_else(|| {
                    panic!(
                        "golden {} has a module-source observation without an origin",
                        path.display()
                    )
                });
                let specifier = value["specifier"].as_str().unwrap_or_else(|| {
                    panic!(
                        "golden {} has a module-source observation without a specifier",
                        path.display()
                    )
                });
                (origin.to_string(), specifier.to_string())
            })
            .collect();
        ExpectedHooks {
            exit_module_imports,
            module_sources,
        }
    } else {
        ExpectedHooks::default()
    };

    (
        projection,
        Projected {
            entry_compartment,
            entry_module,
            compartments,
        },
        expected_hooks,
    )
}

/// Human-readable one-line rendering of a projected map, for diffs.
fn render(p: &Projected) -> String {
    let mut s = format!("entry {}::{}\n", p.entry_compartment, p.entry_module);
    for (name, mods) in &p.compartments {
        s.push_str(&format!("  compartment {name}\n"));
        for (spec, value) in mods {
            s.push_str(&format!("    {spec} => {value}\n"));
        }
    }
    s
}

// Tests

/// The drift safeguard. A fixture on disk but not in [`MANIFEST`] —
/// or a [`MANIFEST`] entry with no directory on disk — fails here, so
/// no fixture can be silently added or removed without a maintainer
/// deciding, on the record, whether it is in scope for the walker.
#[test]
fn no_unaccounted_fixture_drift() {
    let root = fixtures_root();
    let on_disk = on_disk_fixture_dirs(&root);
    let manifest = manifest_fixture_dirs();

    // No fixture may appear twice in the manifest.
    assert_eq!(
        manifest.len(),
        MANIFEST.len(),
        "MANIFEST contains duplicate fixture entries: {:?}",
        {
            let mut seen = BTreeSet::new();
            MANIFEST
                .iter()
                .map(|(n, _)| *n)
                .filter(|n| !seen.insert(*n))
                .collect::<Vec<_>>()
        }
    );

    let unaccounted: Vec<&String> = on_disk.difference(&manifest).collect();
    let stale: Vec<&String> = manifest.difference(&on_disk).collect();

    assert!(
        unaccounted.is_empty(),
        "Unaccounted compartment-mapper fixtures (present on disk but missing from MANIFEST): {unaccounted:?}.\n\
         Add each to MANIFEST in rust/endo/tests/compartment_mapper_fixture_parity.rs as either\n\
         Exercise {{ entry }} (the walker faithfully handles it; commit its expected-compartment-map.json),\n\
         PendingExclude {{ capability: \"…\" }} (name the walker capability group it is blocked on), or\n\
         DurableExclude {{ reason: \"…\" }} (a compartment-mapper-internal concern out of the walker's scope).\n\
         This drift guard exists so a newly added fixture cannot be silently ignored."
    );
    assert!(
        stale.is_empty(),
        "Stale MANIFEST entries (listed here but no such fixture directory on disk): {stale:?}.\n\
         Remove them from MANIFEST in rust/endo/tests/compartment_mapper_fixture_parity.rs."
    );
}

