/// What the parity harness does with one fixture directory.
enum Disposition {
    /// The walker is run against `entry` (a path relative to the
    /// fixture directory) and its compartment map is diffed,
    /// structurally, against the committed golden at
    /// `<fixture>/expected-compartment-map.json` (see
    /// [`exercised_fixtures_match_node_golden`]). Reserved for
    /// fixtures whose reachable graph is expressible through the
    /// walker's supported resolution: static ES `import` / `export …
    /// from`, relative specifiers with the extension/`index`
    /// fall-back, and bare specifiers resolved via `node_modules` with
    /// the `exports["."]` default-string / `main` / `index` cascade.
    Exercise { entry: &'static str },
    /// The walker does not *yet* handle this fixture, but a later
    /// ratchet increment will: `capability` names the walker
    /// capability group (see `designs/endor-run-expanded.md`
    /// § Fixture-parity ratchet) it is blocked on. These shrink toward zero as the campaign
    /// advances — they are the campaign's work queue.
    #[allow(dead_code)] // Kept as the required classification for future fixture drift.
    PendingExclude { capability: &'static str },
    /// The fixture exercises a compartment-mapper-*internal* concern
    /// (a naming strategy, a policy engine, a strict-mode diagnostic, a
    /// deliberate error) that is out of scope for a dependency-walk
    /// parity harness; `reason` says why. These are not chased — they
    /// are the campaign's horizon (`designs/…` §3).
    DurableExclude { reason: &'static str },
}

