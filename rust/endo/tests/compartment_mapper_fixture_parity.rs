//! Compartment-mapper fixture-parity harness for the `endor run
//! <entry.js>` dependency walker (`entry_walk::ingest_entry_point_with_deps`).
//!
//! This crate reimplements a slice of `@endo/compartment-mapper`:
//! the node_modules dependency walk that turns an ES-module entry
//! point into a multi-compartment archive. To establish — and keep
//! honest — parity with the reference implementation, this harness
//! accounts for **every** fixture directory under
//! `packages/compartment-mapper/test`, the same tree the
//! compartment-mapper's own ava suite consumes.
//!
//! It is the substrate for the **fixture-parity ratchet**
//! (`designs/endor-run-expanded.md` § Fixture-parity ratchet): a monotonic campaign
//! from 7-of-40 exercised toward full parity between endor's walker
//! and node's `@endo/compartment-mapper`, capability by capability.
//! Four mechanisms keep the ratchet drift-proof:
//!
//! 1. **Two-tier exclusions.** A non-exercised fixture is either a
//!    [`Disposition::PendingExclude`] (blocked on a named walker
//!    capability that a later increment will land — it *will*
//!    graduate) or a [`Disposition::DurableExclude`] (a
//!    compartment-mapper-internal concern out of the walker's scope —
//!    it will not). The [`scoreboard`] test reports `exercised /
//!    pending / durable`, making campaign progress a measurable number.
//!
//! 2. **No silent drift.** A `fixtures-*` directory on disk but absent
//!    from [`MANIFEST`] — or a manifest entry with no directory —
//!    fails [`no_unaccounted_fixture_drift`]. A newly added fixture
//!    cannot be silently ignored; whoever adds one decides, on the
//!    record, whether it is in scope.
//!
//! 3. **Exercised floor (anti-backslide).** [`EXERCISED_FLOOR`] is a
//!    hard, ratcheting minimum. Each increment that graduates fixtures
//!    raises it; a later change that silently re-excludes a graduated
//!    fixture drops below the floor and fails the suite.
//!
//! 4. **Parity asserted against node, structurally.** An exercised
//!    fixture is no longer checked by a hand-written compartment
//!    *count*. Instead the walker's output is projected to a stable
//!    structural shape (compartment names, per-compartment module
//!    specifiers, and the parser language per module) and diffed
//!    against a committed golden generated by the harness-free node
//!    reference oracle (`rust/endo/tools/gen-parity-golden.mjs`), which
//!    imports `@endo/compartment-mapper` directly. See
//!    [`exercised_fixtures_match_node_golden`].
//!
//! When the walker grows a capability (CommonJS `require`, conditional
//! `exports`, dynamic `import()`, …), the corresponding fixtures move
//! from a `*Exclude` to [`Disposition::Exercise`] here **in the same
//! commit** that lands the capability and commits the fixture's golden,
//! and the floor is bumped. No fixtures graduate in this increment
//! (Increment 0): it lands the oracle, the golden diff, the two-tier
//! split, the floor, and the scoreboard.
//!
//! Per the job that established this harness, the fixtures stay where
//! they live today, under `packages/compartment-mapper/test`; hoisting
//! them into a shared top-level `test/fixtures` tree (as the test262
//! fixtures are arranged) is a deliberately separate, later question.

