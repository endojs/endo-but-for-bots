/// Run the walker against every exercised fixture and diff its
/// compartment map, **structurally**, against the committed golden
/// generated by the node reference oracle
/// (`rust/endo/tools/gen-parity-golden.mjs`). This is the parity
/// surface that grows as the walker gains capabilities. Also enforces
/// the anti-backslide [`EXERCISED_FLOOR`].
/// The emulated harness inputs (condition set + host/exit modules) a
/// fixture is exercised with, supplied *identically* to endor's walker
/// here and to the node reference oracle in
/// `rust/endo/tools/gen-parity-golden.mjs` — the "emulate, don't
/// refactor" rule (`designs/endor-run-expanded.md` § Fixture-parity ratchet). Most
/// fixtures need none; the exceptions:
///
/// - `conditional-host-exports` emulates the `endo:lib` host condition
///   (selecting `lib`'s `exports["endo:lib"]`), which the fixture's own
///   harness passes.
/// - `fixtures-0` admits the entry package's `devDependencies` via the
///   `development` condition and declares `builtin` a host/exit module,
///   matching its `app.agar-make.js` harness options.
/// - `no-trans-dev-deps` explicitly uses `dev: false`, matching the node
///   oracle and proving an installed development-only dependency is not
///   admitted merely because source imports it.
/// - `dynamic-ancestor` enables the entry package's development dependencies,
///   matching the fixture's own dynamic-require harness.
/// - `language-for-extension` registers the `xsonp` → `jsonp` language via
///   the emulated `languageForExtension`, matching the fixture's own
///   `parserForLanguage: { jsonp }` / `languageForExtension: { xsonp: 'jsonp' }`
///   scaffold. `assets` needs no emulated option — `.text`/`.bytes` are
///   default languages and `.uint32` is classified by the entry package's own
///   `"parsers"` map.
/// - `exit` supplies `h2g2:meaning` as executable synthetic source through the
///   exit-module hook, matching the fixture's runtime import hook.
/// - `module-source-hook` supplies the undeclared transitive `dependency-b`
///   through that same exit seam and observes both the file and synthetic
///   sources through the module-source hook.
#[derive(Default)]
struct HookLogs {
    exit_module_imports: Arc<Mutex<Vec<String>>>,
    module_sources: Arc<Mutex<Vec<(String, String)>>>,
}

fn walk_options_for(name: &str) -> (WalkOptions, HookLogs) {
    let logs = HookLogs::default();
    let options = match name {
        "fixtures-conditional-host-exports" => {
            WalkOptions::new(["endo:lib".to_string()], std::iter::empty())
        }
        "fixtures-language-for-extension" => {
            let mut options = WalkOptions::default();
            options
                .language_for_extension
                .insert("xsonp".to_string(), "jsonp".to_string());
            options
        }
        // Emulate the fixture's `browser` condition, activating the browser
        // resolve field on both the node oracle and endor's walker.
        "fixtures-resolve" => WalkOptions::new(["browser".to_string()], std::iter::empty()),
        "fixtures-0" => WalkOptions::new(["development".to_string()], ["builtin".to_string()]),
        "fixtures-dynamic-ancestor" => {
            let mut options = WalkOptions::default();
            options.dev = true;
            options
        }
        "fixtures-common-deps" => {
            // Emulate the fixture's `commonDependencies` harness option:
            // the alias `unlisted-common-dep` resolves to the entry
            // package's `common-dep-target` dependency, available to every
            // package. Supplied identically to the node oracle.
            let mut options = WalkOptions::default();
            options.common_dependencies.insert(
                "unlisted-common-dep".to_string(),
                "common-dep-target".to_string(),
            );
            options
        }
        "fixtures-exit" => {
            let imports = Arc::clone(&logs.exit_module_imports);
            WalkOptions::default().with_exit_module_import_hook(move |request| {
                imports.lock().unwrap().push(request.specifier.to_string());
                Ok((request.specifier == "h2g2:meaning")
                    .then(|| SyntheticModuleSource::new("export const meaning = 42;")))
            })
        }
        "fixtures-module-source-hook" => {
            let imports = Arc::clone(&logs.exit_module_imports);
            let sources = Arc::clone(&logs.module_sources);
            WalkOptions::default()
                .with_exit_module_import_hook(move |request| {
                    imports.lock().unwrap().push(request.specifier.to_string());
                    Ok((request.specifier == "dependency-b").then(|| {
                        SyntheticModuleSource::new(
                            "export const value = 'dependency-b'; export default value;",
                        )
                    }))
                })
                .with_module_source_hook(move |module_source| {
                    let origin = match module_source.origin {
                        ModuleSourceOrigin::File { .. } => "file",
                        ModuleSourceOrigin::SyntheticExit { .. } => "synthetic",
                    };
                    sources
                        .lock()
                        .unwrap()
                        .push((origin.to_string(), module_source.specifier.to_string()));
                    Ok(())
                })
        }
        _ => WalkOptions::default(),
    };
    (options, logs)
}

#[test]
fn exercised_fixtures_match_node_golden() {
    let root = fixtures_root();
    let tmp = tempfile::tempdir().unwrap();

    let mut exercised = 0usize;
    for (name, disp) in MANIFEST {
        let Exercise { entry } = disp else {
            continue;
        };
        exercised += 1;

        let entry_path = root.join(name).join(entry);
        assert!(
            entry_path.is_file(),
            "{name}: exercised entry point {entry} does not exist at {}",
            entry_path.display()
        );

        let golden_path = root.join(name).join("expected-compartment-map.json");
        assert!(
            golden_path.is_file(),
            "{name}: missing golden at {}. Generate it with\n\
             `node rust/endo/tools/gen-parity-golden.mjs {}`.",
            golden_path.display(),
            name.strip_prefix("fixtures-").unwrap_or(name)
        );

        let cas = ContentStore::open(&tmp.path().join(name)).unwrap();
        let (options, hook_logs) = walk_options_for(name);
        let ingested = ingest_entry_point_with_deps_with_options(&cas, &entry_path, &options)
            .unwrap_or_else(|e| panic!("{name}: walker failed on {entry}: {e}"));

        let (projection, want, expected_hooks) = parse_golden(&golden_path);
        assert_eq!(
            *hook_logs.exit_module_imports.lock().unwrap(),
            expected_hooks.exit_module_imports,
            "{name}: exit-module hook observations differ from the node oracle"
        );
        assert_eq!(
            *hook_logs.module_sources.lock().unwrap(),
            expected_hooks.module_sources,
            "{name}: module-source hook observations differ from the node oracle"
        );

        let got = project_endor(&ingested.archive.map, projection);

        assert!(
            got.entry_compartment == want.entry_compartment
                && got.entry_module == want.entry_module
                && got.compartments == want.compartments,
            "{name}: walker output does not match the committed golden.\n\
             --- expected (golden: {}) ---\n{}\n--- actual (endor walker) ---\n{}\n\
             If the walker's behaviour changed on purpose, regenerate the golden with\n\
             `node rust/endo/tools/gen-parity-golden.mjs {}` (node-oracle fixtures) or update the\n\
             committed endor-baseline golden by hand (fixtures whose golden.oracle is \"endor-baseline\").",
            golden_path.display(),
            render(&want),
            render(&got),
            name.strip_prefix("fixtures-").unwrap_or(name),
        );

        if matches!(*name, "fixtures-exit" | "fixtures-module-source-hook") {
            xsnap::run_xs_archive_loaded(&ingested.archive).unwrap_or_else(|error| {
                panic!("{name}: emulated host source did not execute: {error}")
            });
        }
    }

    // Anti-backslide: the exercised set must never drop below the
    // ratcheting floor. A change that silently re-excludes a graduated
    // fixture trips this.
    assert!(
        exercised >= EXERCISED_FLOOR,
        "exercised fixtures ({exercised}) fell below the ratchet floor ({EXERCISED_FLOOR}); \
         a graduated fixture was re-excluded. Restore it, or (with maintainer sign-off) lower \
         EXERCISED_FLOOR — but backsliding the parity campaign should be deliberate, not silent."
    );
}

/// The parity scoreboard: prints `exercised / pending / durable` so
/// campaign progress is a visible number, and cross-checks the tallies
/// against the manifest size and the exercised floor.
#[test]
fn scoreboard() {
    let mut exercised = 0usize;
    let mut pending = 0usize;
    let mut durable = 0usize;
    for (_, disp) in MANIFEST {
        match disp {
            Exercise { .. } => exercised += 1,
            PendingExclude { .. } => pending += 1,
            DurableExclude { .. } => durable += 1,
        }
    }

    let total = MANIFEST.len();
    println!(
        "compartment-mapper fixture parity scoreboard: \
         {exercised} exercised / {pending} pending / {durable} durable  (of {total} fixtures)"
    );
    println!(
        "  campaign horizon: {} fixtures still to graduate (pending); \
         {durable} durably out of the walker's scope",
        pending
    );

    assert_eq!(
        exercised + pending + durable,
        total,
        "scoreboard tallies ({exercised}+{pending}+{durable}) do not sum to the manifest size ({total})"
    );
    assert!(
        exercised >= EXERCISED_FLOOR,
        "scoreboard: exercised ({exercised}) is below the ratchet floor ({EXERCISED_FLOOR})"
    );
}

/// `fixtures-no-name` proves the walker's unnamed-package handling:
