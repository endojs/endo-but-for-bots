const matchSymbols = buildString({
  loneCodePoints: [],
  ranges: [
    [0x000000, 0x00007F]
  ]
});
testPropertyEscapes(
  /^\p{ASCII}+$/u,
  matchSymbols,
  "\\p{ASCII}"
);

const nonMatchSymbols = buildString({
  loneCodePoints: [],
  ranges: [
    [0x00DC00, 0x00DFFF],
    [0x000080, 0x00DBFF],
    [0x00E000, 0x10FFFF]
  ]
});
testPropertyEscapes(
  /^\P{ASCII}+$/u,
  nonMatchSymbols,
  "\\P{ASCII}"
);
