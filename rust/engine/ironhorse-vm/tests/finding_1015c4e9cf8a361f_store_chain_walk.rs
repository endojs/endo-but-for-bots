/// The `bytecode_decoder` harness's dispatch ceiling
/// (`ironhorse_fuzz::DECODER_STEP_LIMIT`).
const DECODER_STEP_LIMIT: u64 = 2_000_000;

#[test]
fn repeated_store_into_one_chain_halts_well_below_the_dispatch_ceiling() {
    let out = run_program_bounded(&INPUT, DECODER_STEP_LIMIT);
    assert!(
        matches!(out.halt, Halt::StepLimit(_)),
        "the store-chain walk must halt as a bounded StepLimit, got {:?}",
        out.halt
    );
    assert!(
        out.dispatched < 100_000,
        "the chain ceiling must trip long before the dispatch ceiling: {}",
        out.dispatched
    );
}

#[test]
fn short_store_chains_run_to_the_dispatch_ceiling_unchanged() {
    // Early rounds have chains far shorter than the ceiling, so a small
    // dispatch limit is what stops them, exactly as before the guard.
    let out = run_program_bounded(&INPUT, 10_000);
    assert_eq!(out.halt, Halt::StepLimit(10_000));
    assert_eq!(out.dispatched, 10_000);
}
