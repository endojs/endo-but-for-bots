/// Port of `fxIsIdentifierFirst`: is `c` a valid identifier-start code
/// point (ASCII `$`/`_`/letters plus the Unicode `ID_Start` set XS ships)?
pub fn is_identifier_first(c: u32) -> bool {
    let mut s: u32 = 0;
    let table = IDENTIFIER_FIRST;
    let mut i = 0;
    while i < table.len() {
        s += table[i] as u32;
        if c < s {
            return false;
        }
        s += table[i + 1] as u32;
        if c <= s {
            return true;
        }
        i += 2;
    }
    false
}

/// Port of `fxIsIdentifierNext`: is `c` a valid identifier-continue code
/// point? Includes the trailing out-of-table range pair XS appends after
/// the loop.
pub fn is_identifier_next(c: u32) -> bool {
    let mut s: u32 = 0;
    let table = IDENTIFIER_NEXT;
    let mut i = 0;
    while i < table.len() {
        s += table[i] as u32;
        if c < s {
            return false;
        }
        s += table[i + 1] as u32;
        if c <= s {
            return true;
        }
        i += 2;
    }
    // The final pair XS adds past the u16 table (see module doc).
    s += 707719;
    if c < s {
        return false;
    }
    s += 239;
    c <= s
}
